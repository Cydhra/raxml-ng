#ifndef RAXML_EBGFILTER_HPP
#define RAXML_EBGFILTER_HPP

#include "../../Options.hpp"
#include "../start/TreeSource.hpp"

#include "../../Tree.hpp"
#include "../../bootstrap/SplitsTree.hpp"
#include "../../bootstrap/EbgSupportTree.hpp"

/** A vector of bit-vectors (stored as a vector of corax_split_base_t). Each bit vector is one split from the tree. */
using Split = std::vector<corax_split_base_t>;

using SplitList = std::vector<Split>;

struct RaxmlInstance;

// forward declaration of generate_tree in main.cpp to make it accessible. If the function in main.cpp
// changes signature, just update this declaration as well.
Tree generate_tree(const RaxmlInstance &instance, StartingTree type, unsigned int random_seed, bool bootstrap);

class CandidateEbgSupportTree : public EbgSupportTree {
public:
    using EbgSupportTree::EbgSupportTree;
    bool compute() { return compute_support(); }
    const corax_split_t *reference_splits() const { return _ref_splits.get(); }
};

/**
 * Helper struct to rank candidates using a score during filtering
 */
struct RankedCandidate {
    Tree tree;
    unsigned int promise_score = 0;
};

/**
 * Verifies that a list of candidate trees approximates the per-split bootstrap distribution estimated by EBG.
 * This serves to avoid using TreeSources which generate a strongly biased selection of trees which does not reflect
 * the expected distribution of splits.
 */
class EbgGate {
public:
    EbgGate(const Options &opts, Tree baseline_tree, TreeList initial_ml_trees)
        : baseline_tree(std::move(baseline_tree)),
          initial_ml_trees(std::move(initial_ml_trees)), mae_margin(opts.gate_margin) {
    }

    /**
     * Initialize the EBG gate with an EBG support tree and split frequencies. Calling this method multiple times has
     * no effect. To re-initialize with different support trees, call `reset_gate`.
     *
     * @param instance RaxmlInstance to generate parsimony trees
     * @param support_trees The parsimony trees we use to generate EBG support values. Use a different range to reset the gate to new values
     * @param barrier a thread barrier over all threads involved in the gate instantiation
     * @param num_workers number of threads involved in the gate instantiation. For this method, workers and threads are equivalent, so each thread must be treated as a worker
     * @param worker_id thread id (global, not per worker) of the current thread
     */
    void init_gate(const RaxmlInstance &instance, const ConstTreeRange & support_trees, const SmartBarrier &barrier, unsigned int
                    num_workers, unsigned int worker_id);

    /**
     * Reset the EBG gate with new EBG support values and calculate split frequencies.
     * This can be called multiple times to instantiate the gate with a new EBG support tree.
     *
     * @param instance RaxmlInstance to generate parsimony trees
     * @param support_trees The parsimony trees we use to generate EBG support values. Use a different range to reset the gate to new values
     * @param barrier a thread barrier over all threads involved in the gate instantiation
     * @param num_workers number of threads involved in the gate instantiation. For this method, workers and threads are equivalent, so each thread must be treated as a worker
     * @param worker_id thread id (global, not per worker) of the current thread
     */
    void reset_gate(const RaxmlInstance &instance, const ConstTreeRange & support_trees, const SmartBarrier &barrier, unsigned int
                    num_workers, unsigned int worker_id);

    /**
     * Gate the candidate list.
     * That is, check whether the distribution of split frequencies in the candidate list matches the expected
     * distribution generated by EBG.
     * If it does, the candidates are ranked and sorted by their promise, i.e., splits with higher support are moved
     * and an updated list is returned.
     *
     * @param candidates mutable list of candidate
     * @return
     */
    TreeList gate_and_rank(TreeList candidates);

protected:
    /**
     * Best ML tree from reference set to use as the EBG filter reference.
     * This instance must not be accessed by multiple threads at once because Tree is not thread-safe.
     */
    Tree baseline_tree;

    /**
     * Set of reference ML trees
     */
    TreeList initial_ml_trees;

    /**
     * Splits extracted from reference ML trees, projected onto a reference tree
     */
    std::shared_ptr<CandidateEbgSupportTree> reference_support_tree;

    TreeList bootstrap_support_trees;

    /**
     * Frequencies of splits in ML trees (referenced by index of split)
     */
    std::vector<double> ml_frequency;

    /**
     * EBG support values of splits (referenced by index of split)
     */
    std::vector<double> ebg_support;

    /**
     * Margin for acceptable mean absolute error of EBG support from ml_frequency, which are accepted during filtering
     */
    double mae_margin;
};


#endif //RAXML_EBGFILTER_HPP

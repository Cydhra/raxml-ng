#include "TreesetHeuristic.hpp"

#include <climits>

#include "TunedBatch.hpp"

constexpr unsigned int BATCH_SIZE = 32;

/**
 * A collection of measurements associated with one TunedBatch instance.
 * The benchmark tracks a series of wall-times for tree inference and the improvements in plausible tree counts.
 *
 * We can use those times to obtain the best parameters for batches that will yield the most plausible trees with the
 * least wall-time spent.
 */
class BatchBenchmark {
public:
    std::vector<unsigned int> plausible_tree_counts{};
    std::vector<unsigned int> cost{};

    /**
     * Add a data point to the benchmark.
     * @param plausible_trees How many plausible trees were reached (total)
     * @param wall_time How many nanoseconds did it take to obtain the plausible tree count (total)
     */
    void add_data_point(const unsigned int plausible_trees, const unsigned int wall_time) {
        plausible_tree_counts.push_back(plausible_trees);
        cost.push_back(wall_time / plausible_trees);
    }

    /**
     * Get the index of the data point where the cost (i.e. the time spent per plausible tree) is lowest.
     * @return 0-based index of the datapoint of minimum time spent per plausible tree.
     */
    unsigned int get_cheapest_point() const {
        return distance(cost.begin(), min_element(cost.begin(), cost.end()));
    }

    /**
     * Calculate the cost of improving the plausible tree set from the starting trees into the plausible tree set at
     * the data point returned by get_cheapest_point.
     * This allows comparing benchmarks across different starting tree sets: If a set has more plausible starting trees,
     * it is probable that it will also have more plausible trees after N SPR rounds.
     * But this doesn't mean that the parameters that were used during benchmarking are better, so to compare parameters,
     * we compare the cost of adding trees to the plausible set.
     *
     * @return Milliseconds per tree added to the plausible tree set over the starting tree set, after N SPR rounds,
     *         where N is the point of lowest cost.
     */
    unsigned int cost_of_improvement() const {
        const auto cheapest_point = get_cheapest_point();
        const auto improvement_count = plausible_tree_counts[cheapest_point] - plausible_tree_counts[0];

        if (improvement_count == 0) {
            return UINT_MAX;
        }

        return (cost[cheapest_point] - cost[0]) / improvement_count;
    }

    /**
     * @return Returns true, if the last two data points did not improve the time-per-plausible-tree metric,
     *         meaning doing more work does not speed up computation.
     */
    bool is_converged() const {
        const auto min = min_element(cost.begin(), cost.end());
        return distance(min, cost.end()) > 1;
    }
};

void TreesetHeuristic::infer_treeset(RaxmlInstance &instance, const Options &opts, CheckpointManager &cm,
                                     LoadBalancer &load_balancer) {
    // copy SPR parameters from local search state
    auto search_state = SearchState();
    auto &spr_params = search_state.spr_params;
    spr_params.ntopol_keep = 20;
    spr_params.subtree_cutoff = opts.spr_cutoff;
    spr_params.radius_min = 0;
    spr_params.radius_max = 20;
    spr_params.thorough = false;
    spr_params.lh_epsilon_brlen_full = opts.lh_epsilon;
    spr_params.lh_epsilon_brlen_triplet = opts.lh_epsilon_brlen_triplet;

    // generate trees depending on the seed. Note that the normal starting trees are generated by seeding srand() and
    // then generating seeds using rand(), so we won't be creating duplicates by starting over from the random_seed.
    auto seed_offset = opts.random_seed;

    // step 1: we need to prepare a set of batches so that we can use batches of similar starting tree plausibility for
    // the tuning phase
    std::vector<TunedBatch> all_batches;

    // TODO add constant for the number of batches
    for (auto i = 0; i < 8; ++i) {
        all_batches.emplace_back(TunedBatch(false, false, 0, seed_offset, BATCH_SIZE, spr_params,
                                            this->recommended_thread_count(), this->recommended_worker_count(), msa,
                                            persite_loglh));
        auto &batch = all_batches.back();
        seed_offset += BATCH_SIZE;
        batch.generate_starting_trees(instance, opts, load_balancer, tip_msa_idmap);

        // calling infer_batch with target num_spr set to 0 will only perform a single model optimization
        batch.optimize_model(opts);
        auto plausible_tree_count = batch.perform_au_test(opts);
        LOG_INFO << "Plausible Starting Trees: " << plausible_tree_count << std::endl;
    }

    // benchmarks during tuning
    std::vector<BatchBenchmark> benchmarks;

    while (tuning_phase != FINALIZED) {
        auto batch = TunedBatch(this->greedy_spr, this->skip_model, this->num_spr, seed_offset, BATCH_SIZE, spr_params,
                                this->recommended_thread_count(),
                                this->recommended_worker_count(), msa, persite_loglh);
        LOG_INFO_TS << "Inferring " << batch.get_batch_size() << " trees in batch for phase " << tuning_phase <<
                std::endl;

        seed_offset += BATCH_SIZE;
        batch.generate_starting_trees(instance, opts, load_balancer, tip_msa_idmap);
        batch.optimize_model(opts);

        BatchBenchmark benchmark;

        switch (tuning_phase) {
            case TUNE_BASELINE:
                if (batch.is_plausible(opts)) {
                    LOG_INFO_TS << "Most starting trees are already plausible; topology optimization unnecessary" <<
                            std::endl;
                    this->accept_starting_trees = true;
                    tuning_phase = FINALIZED;
                    break;
                }

                LOG_INFO_TS << "Starting trees generally implausible; topology optimization necessary" << std::endl;

                do {
                    benchmark.add_data_point(batch.plausible_tree_count(), batch.elapsed_wall_time());

                    this->num_spr += 1;
                    batch.target_num_spr = this->num_spr;
                    batch.optimize_topology(opts);
                } while (!batch.is_plausible(opts) && !benchmark.is_converged());

                LOG_INFO_TS << "FAST SPR rounds create cheapest improvement after " << benchmark.get_cheapest_point() <<
                        " SPR rounds." << std::endl;

                tuning_phase = TUNE_GREEDY;
                this->greedy_spr = true;
                // reset spr for the greedy round measurement
                this->num_spr = 0;
                break;
            case TUNE_GREEDY:
                // do AU test
                if (batch.is_plausible(opts)) {
                    // now we have a problem: we ran into a plausible batch by starting trees, but this did not happen
                    // on the last batch, so we cannot rely on it.
                    LOG_WARN << "GREEDY SPR benchmark prevented by plausible starting tree set." << std::endl;
                    // TODO add the set to the batches and redraw trees?
                }

                do {
                    benchmark.add_data_point(batch.plausible_tree_count(), batch.elapsed_wall_time());

                    this->num_spr += 1;
                    batch.target_num_spr = this->num_spr;
                    batch.optimize_topology(opts);
                } while (!batch.is_plausible(opts) && !benchmark.is_converged());

                LOG_INFO_TS << "GREEDY SPR rounds create cheapest improvement after " << benchmark.get_cheapest_point()
                        << " SPR rounds." << std::endl;

                if (benchmark.is_converged()) {
                    LOG_INFO_TS << "after " << benchmark.get_cheapest_point() <<
                            " GREEDY spr rounds, plausibility converged."
                            << std::endl;

                    const auto fast_cost = benchmarks.back().cost_of_improvement();
                    const auto greedy_cost = benchmark.cost_of_improvement();

                    LOG_DEBUG_TS << "FAST SPR rounds improvement cost: " << fast_cost <<
                            "; GREEDY SPR rounds improvement cost: " << greedy_cost << std::endl;

                    if (fast_cost < greedy_cost) {
                        LOG_INFO_TS <<
                                "FAST SPR rounds provider cheaper improvement than GREEDY SPR rounds. Disabling GREEDY search."
                                << std::endl;
                        this->greedy_spr = false;
                        this->num_spr = benchmarks.back().get_cheapest_point();
                    } else {
                        LOG_INFO_TS <<
                                "GREEDY SPR rounds provider cheaper improvement than FAST SPR rounds. Keeping GREEDY search."
                                << std::endl;
                        this->num_spr = benchmark.get_cheapest_point();
                    }
                } else {
                    LOG_WARN << benchmark.get_cheapest_point() <<
                            " GREEDY spr rounds saturated the benchmark. Keeping GREEDY search." << std::endl;
                    this->num_spr = benchmark.get_cheapest_point();
                }

                this->skip_model = true;
                this->tuning_phase = TUNE_MODEL_OPT;
                break;
            case TUNE_MODEL_OPT:
                batch.inherit_model(*(all_batches.end() - 1));
                batch.optimize_topology(opts);
                if (!batch.is_plausible(opts)) {
                    LOG_INFO_TS <<
                            "Skipping model optimization yielded implausible trees, reverting to per-tree model optimization."
                            << std::endl;
                    this->skip_model = false;
                } else {
                    LOG_INFO_TS <<
                            "Skipping model optimization yielded plausible trees, disabling per-tree model optimization."
                            << std::endl;
                }

                this->tuning_phase = FINALIZED;
                break;
            case FINALIZED:
                break;
        }

        all_batches.push_back(std::move(batch));
        benchmarks.push_back(std::move(benchmark));
        LOG_INFO << std::endl;
    }

    LOG_INFO_TS << "treeset inference complete." << std::endl;
}

int TreesetHeuristic::recommended_thread_count() {
    // TODO add parameters to options containing the max thread count, which we just assign to the single worker per rank
    return 8;
}

int TreesetHeuristic::recommended_worker_count() {
    // TODO this is only true for the tuning phase
    return 1;
}
